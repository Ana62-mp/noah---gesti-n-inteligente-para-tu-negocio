// Helper to generate 60 days of sales
export const generateSalesHistory = (): Sale[] => {
  const sales: Sale[] = [];
  const paymentMethods: Sale['paymentMethod'][] = ['cash', 'card', 'transfer', 'deuna'];
  const channels: Sale['channel'][] = ['salon', 'salon', 'salon', 'takeout', 'delivery'];
  const waiters = ['Ana', 'Jorge', 'Lucía', 'Pedro'];

  // Today's specific target: $780.50 in 86 orders, lunch peak $352.00
  // Generate 86 sales for today (2026-11-03)
  let todayTotal = 0;
  for (let i = 1; i <= 86; i++) {
    const isLunch = i >= 25 && i <= 60;
    const hour = isLunch ? 12 + Math.floor(Math.random() * 2) : 9 + Math.floor(Math.random() * 11);
    const minute = Math.floor(Math.random() * 60).toString().padStart(2, '0');
    const timeStr = `${hour.toString().padStart(2, '0')}:${minute}`;

    const dish = DISHES_MOCK[i % DISHES_MOCK.length];
    const qty = 1 + (i % 3);
    const subtotal = dish.sellingPrice * qty;
    const tax = subtotal * 0.15;
    const total = subtotal;

    sales.push({
      id: `sale-today-${i}`,
      date: '2026-11-03',
      time: timeStr,
      channel: channels[i % channels.length],
      tableNumber: (i % 12) + 1,
      waiterName: waiters[i % waiters.length],
      items: [
        {
          dishId: dish.id,
          dishName: dish.name,
          quantity: qty,
          unitPrice: dish.sellingPrice,
          subtotal,
        },
      ],
      subtotal,
      tax,
      total,
      paymentMethod: paymentMethods[i % paymentMethods.length],
      status: 'completed',
    });
    todayTotal += total;
  }

  // Generate previous days
  for (let dayOffset = 1; dayOffset <= 59; dayOffset++) {
    const d = new Date(2026, 10, 3 - dayOffset);
    const dateStr = d.toISOString().split('T')[0];
    const isWeekend = d.getDay() === 0 || d.getDay() === 6;
    const isWed = d.getDay() === 3;
    const count = isWeekend ? 65 : isWed ? 35 : 48;

    for (let j = 1; j <= count; j++) {
      const dish = DISHES_MOCK[(j + dayOffset) % DISHES_MOCK.length];
      const qty = 1 + ((j * dayOffset) % 2);
      const subtotal = dish.sellingPrice * qty;
      sales.push({
        id: `sale-${dayOffset}-${j}`,
        date: dateStr,
        time: `${12 + (j % 8)}:${((j * 7) % 60).toString().padStart(2, '0')}`,
        channel: channels[j % channels.length],
        tableNumber: (j % 12) + 1,
        waiterName: waiters[j % waiters.length],
        items: [
          {
            dishId: dish.id,
            dishName: dish.name,
            quantity: qty,
            unitPrice: dish.sellingPrice,
            subtotal,
          },
        ],
        subtotal,
        tax: subtotal * 0.15,
        total: subtotal,
        paymentMethod: paymentMethods[j % paymentMethods.length],
        status: 'completed',
      });
    }
  }

  return sales;
};

